/** Local, pinned MIT Bootstrap. Native @scope contains reboot, tokens and components. */
import fs from 'node:fs'
import postcss from 'postcss'

const source = 'node_modules/bootstrap/dist/css/bootstrap.css'
const header = '/* Generated by scripts/build-batch2-bs6.mjs. Bootstrap MIT, v6.0.0-alpha.1. */\n'

function scoped(scopeSelector) {
  const css = postcss.parse(fs.readFileSync(source, 'utf8'))
  css.walkAtRules('charset', rule => rule.remove())
  css.walkRules(rule => {
    if (rule.parent?.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return
    rule.selectors = rule.selectors.map(sel => sel.replace(/:root|:host|(?<![\w-])(?:html|body)(?![\w-])/g, ':scope'))
  })
  const scope = postcss.atRule({ name: 'scope', params: `(${scopeSelector})` })
  scope.append(css.nodes)
  return header + scope.toString() + '\n'
}

fs.writeFileSync('.vitepress/theme/batch2-bs6.bootstrap.css', scoped('.b2-bs6'))
fs.writeFileSync('.vitepress/theme/relay-bs6.bootstrap.css', scoped('.relay-bs6'))
