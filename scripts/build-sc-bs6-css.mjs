/**
 * Scope Bootstrap 6.0.0-alpha.1 to `.sc` and `.sc-bs6-portal` so it never bleeds into VitePress chrome.
 * Regenerate after bumping the bootstrap dependency.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import postcss from 'postcss'
import prefixSelector from 'postcss-prefix-selector'

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const src = path.join(root, 'node_modules/bootstrap/dist/css/bootstrap.min.css')
const out = path.join(root, '.vitepress/theme/sc-bs6-core.css')

const scope = '.sc'

const input = fs.readFileSync(src, 'utf8')
const result = await postcss([
  prefixSelector({
    prefix: scope,
    transform(prefix, selector, prefixedSelector) {
      if (selector === ':root' || selector === ':host') return scope
      if (selector === 'html' || selector === 'body') return selector
      return prefixedSelector
    },
  }),
]).process(input, { from: src })
const merged = result.css

const banner = `/* Bootstrap 6.0.0-alpha.1 scoped to .sc — generated by scripts/build-sc-bs6-css.mjs */\n`
fs.writeFileSync(out, banner + merged)
console.log('Wrote', out, `(${Math.round(merged.length / 1024)} KiB)`)
