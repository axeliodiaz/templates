/**
 * Scope Bootstrap 6.0.0-alpha.1 to `.bst-root` for the Bastion template.
 * Reboot selectors (`:root`, `html`, `body`) become `:scope` so the
 * VitePress shell and other languages (including Bootstrap 5 pages) are untouched.
 * The alpha stylesheet uses `@layer` and `@media`; both stay inside `@scope`.
 */
import fs from 'node:fs'
import postcss from 'postcss'

const source = 'node_modules/bootstrap/dist/css/bootstrap.css'
const css = postcss.parse(fs.readFileSync(source, 'utf8'))
css.walkAtRules('charset', (rule) => rule.remove())
css.walkRules((rule) => {
  if (rule.parent?.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return
  rule.selectors = rule.selectors.map((selector) =>
    selector.replace(/:root|:host|(?<![\w-])(?:html|body)(?![\w-])/g, ':scope'),
  )
})
const scope = postcss.atRule({ name: 'scope', params: '(.bst-root)' })
scope.append(css.nodes)
const banner = '/* Generated by scripts/build-bastion-bs6.mjs. Bootstrap MIT, v6.0.0-alpha.1. Scoped to .bst-root. Do not edit. */\n'
fs.writeFileSync('.vitepress/theme/bastion-bs6.bootstrap.css', banner + scope.toString() + '\n')
console.log('Wrote .vitepress/theme/bastion-bs6.bootstrap.css')
